// ─────────────────────────────────────────────────────────────────────
// Utility: re-encode an LF-normalized injection block to the host's EOL.
// ─────────────────────────────────────────────────────────────────────
function toEol(text, useCRLF) {
  const lf = text.replace(/\r\n/g, '\n');
  return useCRLF ? lf.replace(/\n/g, '\r\n') : lf;
}

// ─────────────────────────────────────────────────────────────────────
// Find balanced bracket end. Returns index of matching closer or -1.
// Skips over single/double/back-ticked strings and // + /* comments.
// ─────────────────────────────────────────────────────────────────────
function findBalanced(text, openIdx) {
  const open = text[openIdx];
  const close = open === '[' ? ']' : open === '{' ? '}' : open === '(' ? ')' : null;
  if (!close) return -1;
  let depth = 0;
  let i = openIdx;
  const n = text.length;
  while (i < n) {
    const ch = text[i];
    // Strings
    if (ch === '"' || ch === "'" || ch === '`') {
      const quote = ch;
      i++;
      while (i < n && text[i] !== quote) {
        if (text[i] === '\\') { i += 2; continue; }
        // Template-literal interpolation: ${ ... }
        if (quote === '`' && text[i] === '$' && text[i + 1] === '{') {
          i = findBalanced(text, i + 1);
          if (i < 0) return -1;
          i++; continue;
        }
        i++;
      }
      i++; continue;
    }
    // Line comment
    if (ch === '/' && text[i + 1] === '/') {
      while (i < n && text[i] !== '\n') i++;
      continue;
    }
    // Block comment
    if (ch === '/' && text[i + 1] === '*') {
      i += 2;
      while (i < n && !(text[i] === '*' && text[i + 1] === '/')) i++;
      i += 2; continue;
    }
    if (ch === open)  depth++;
    if (ch === close) { depth--; if (depth === 0) return i; }
    i++;
  }
  return -1;
}

