// ─────────────────────────────────────────────────────────────────────
function runValidator(scriptPath, targetPath) {
  try {
    const out = cp.execFileSync(process.execPath, [scriptPath, targetPath], {
      stdio: ['ignore', 'pipe', 'pipe'],
      encoding: 'utf8'
    });
    return { ok: true, output: out };
  } catch (e) {
    return { ok: false, output: (e.stdout || '') + (e.stderr || '') + (e.message || '') };
  }
}

// ─────────────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────────────
function main() {
  const argPath = process.argv[2];
  if (!argPath) {
    console.error('Usage: node patch_glossary_v1.js <path-to-index.html>');
    process.exit(2);
  }
  const target = path.resolve(argPath);
  if (!fs.existsSync(target)) {
    console.error('File not found:', target);
    process.exit(2);
  }

  const raw0 = fs.readFileSync(target, 'utf8');
  const crlfCount = (raw0.match(/\r\n/g) || []).length;
  const lfCount   = (raw0.match(/\n/g) || []).length;
  const useCRLF = crlfCount > lfCount / 2; // dominant if >= half of all \n are CRLF
  console.log(C_DIM + 'EOL: ' + (useCRLF ? 'CRLF' : 'LF') +
    ' (' + crlfCount + ' \\r\\n / ' + lfCount + ' \\n)' + C_RST);

  // Backup once.
  const backup = target + '.bak-glossary-v1';
  if (!fs.existsSync(backup)) {
    fs.writeFileSync(backup, raw0);
    console.log(C_DIM + 'Backup written: ' + backup + C_RST);
  } else {
    console.log(C_DIM + 'Backup preserved: ' + backup + C_RST);
  }

  let raw = raw0;
  const working = raw.replace(/<!--[\s\S]*?-->/g, '');

  const ops = [
    { id: 'a', name: 'CSS injection',           fn: patchCSS },
    { id: 'b', name: 'View div injection',      fn: patchViewDiv },
    { id: 'c', name: 'Tab registration',        fn: patchTabRegistration },
    { id: 'd', name: 'COURSE_CONFIG placeholder', fn: patchPlaceholder },
    { id: 'e', name: 'JS bundle',               fn: patchJSBundle },
    { id: 'f', name: 'data-id on graph nodes',  fn: patchDataId },
    { id: 'g', name: 'dd-nav move',             fn: patchDdNavMove },
  ];

  const results = [];
  for (const op of ops) {
    // re-derive working copy after each mutation so subsequent searches stay accurate
    const work = raw.replace(/<!--[\s\S]*?-->/g, '');
    const r = op.fn(raw, work, useCRLF);
    if (r.raw) raw = r.raw;
    results.push({ id: op.id, name: op.name, status: r.status, reason: r.reason || '' });
  }

  // Write if anything changed.
  const changed = raw !== raw0;
  if (changed) fs.writeFileSync(target, raw);

  // ── Validation ──────────────────────────────────────────────────
  const hereDir = __dirname;
  const vq = path.join(hereDir, 'verify_quiz.js');
  const vc = path.join(hereDir, 'verify_config.js');

  let quizRes = { ok: true, output: '(skipped — verify_quiz.js missing)' };
  let cfgRes  = { ok: true, output: '(skipped — verify_config.js missing)' };
  if (fs.existsSync(vq)) quizRes = runValidator(vq, target);
  if (fs.existsSync(vc)) cfgRes  = runValidator(vc, target);

  // Syntax check on each inline <script>
  const syn = syntaxCheckScripts(raw);

  // ── Report ──────────────────────────────────────────────────────
  console.log('');
  console.log(C_DIM + '─── Patch Summary ───────────────────────────' + C_RST);
  for (const r of results) {
    const tag =
      r.status === 'applied' ? (C_GRN + 'applied' + C_RST) :
      r.status === 'skipped' ? (C_YEL + 'skipped' + C_RST) :
                                (C_RED + 'error'   + C_RST);
    const rsn = r.reason ? '  ' + C_DIM + '(' + r.reason + ')' + C_RST : '';
    console.log('  (' + r.id + ') ' + r.name.padEnd(30) + '  ' + tag + rsn);
  }
  console.log('');
  console.log(C_DIM + '─── Validators ──────────────────────────────' + C_RST);
  console.log('  verify_quiz.js   : ' +
    (quizRes.ok ? (C_GRN + 'PASS' + C_RST) : (C_RED + 'FAIL' + C_RST)));
  if (!quizRes.ok) console.log(quizRes.output.split('\n').map(l => '    ' + l).join('\n'));
  console.log('  verify_config.js : ' +
    (cfgRes.ok ? (C_GRN + 'PASS' + C_RST) : (C_RED + 'FAIL' + C_RST)));
  if (!cfgRes.ok) console.log(cfgRes.output.split('\n').map(l => '    ' + l).join('\n'));

  console.log('');
  console.log(C_DIM + '─── Script Syntax ───────────────────────────' + C_RST);
  console.log('  ' + syn.total + ' scripts checked, ' +
    (syn.failed === 0 ? (C_GRN + '0' + C_RST) : (C_RED + syn.failed + C_RST)) +
    ' failed');
  for (const e of syn.errors) console.log('    ' + C_RED + e + C_RST);

  // ── Exit ────────────────────────────────────────────────────────
  const allOk =
    results.every(r => r.status !== 'error') &&
    quizRes.ok && cfgRes.ok && syn.failed === 0;
  console.log('');
  console.log(allOk ? (C_GRN + '✓ glossary v1 patch complete' + C_RST)
                    : (C_RED + '✗ glossary v1 patch finished with issues' + C_RST));
  process.exit(allOk ? 0 : 1);
}

if (require.main === module) main();
